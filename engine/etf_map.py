def all_etf_secids() -> list:
    seen, out = set(), []
    for cands in SW_ETF_CANDIDATES.values():
        for sid, name, _m in cands:
            if sid not in seen:
                seen.add(sid)
                out.append((sid, name))
    for proxy in L2_PROXY.values():
        if isinstance(proxy, list):
            for sid, _m in proxy:
                if sid not in seen:
                    seen.add(sid)
                    out.append((sid, sid))
    for sid, name in BENCH_ETF.items():
        if sid not in seen:
            seen.add(sid)
            out.append((sid, name))
    return out


def all_keys() -> List[str]:
    """所有需要构建「可交易标的」的 key：一级行业 + 细分赛道。"""
    keys = list(SW_ETF_CANDIDATES.keys())
    for k in L2_PROXY:
        if k not in keys:
            keys.append(k)
    return keys
