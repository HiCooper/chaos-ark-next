def resolve_candidates(key: str) -> List[Tuple[str, str, float]]:
    """给定行业名（一级或细分赛道），返回候选 [(secid, 说明, match)]。

    细分赛道优先用自己的 ETF；没有时退回所属一级行业的候选。
    """
    if key in SW_ETF_CANDIDATES:
        return list(SW_ETF_CANDIDATES[key])
    p = L2_PROXY.get(key)
    if isinstance(p, list):
        return [(sid, f"{key}ETF", m) for sid, m in p]
    if isinstance(p, str):
        return list(SW_ETF_CANDIDATES.get(p, []))
    return []


def resolve_l1(key: str) -> Optional[str]:
    """反查该赛道所属的一级行业（用于披露代理关系）。"""
    if key in SW_ETF_CANDIDATES:
        return key
    p = L2_PROXY.get(key)
    return p if isinstance(p, str) else None


